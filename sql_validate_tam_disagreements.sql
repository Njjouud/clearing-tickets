    WHEN 'REFUND_ADJST' THEN 'SHOULD_REFUND_ADJST_RULE'
    WHEN 'GLOBALBLUE' THEN 'SHOULD_GLOBALBLUE_MERCHANT_CLOSE'
    ELSE 'UNKNOWN'
  END AS expected_fix,
  LEFT(a.resolution, 120) AS resolution_preview,
  a.updated_at
