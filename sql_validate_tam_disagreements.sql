INNER JOIN jake_exploration.tickets_agent__agent_work a
  ON CAST(a.sr_number AS BIGINT) = d.sr_num
 AND a.model = 'tickets-engine'
LEFT JOIN polaris.`base.oci_crm_db`.all_service_requests t
  ON CAST(t.SrNumber AS BIGINT) = d.sr_num
ORDER BY d.tam_bucket, a.updated_at DESC;

