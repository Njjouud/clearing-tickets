  a.route AS engine_route,
  CASE WHEN a.facts LIKE '%is_hold_account=1%' THEN 1 ELSE 0 END AS is_hold,
  CASE WHEN a.facts LIKE '%is_settle_account=1%' THEN 1 ELSE 0 END AS is_settle,
  CASE
    WHEN LOWER(a.facts) LIKE '%provider_account_name=mada%' THEN 'MADA'
    WHEN LOWER(a.facts) LIKE '%provider_account_name=visa%' THEN 'VISA'
    ELSE 'OTHER'
  END AS scheme_from_account,
  CASE
    WHEN a.facts LIKE '%txn_type=UNACRE%' THEN 'UNACRE'
    WHEN a.facts LIKE '%txn_type=REFUND%' THEN 'REFUND'
    WHEN a.facts LIKE '%txn_type=DEBIT%' THEN 'DEBIT'
    ELSE 'OTHER'
  END AS txn_type,
  CASE
    WHEN a.ticket_status = 'Closed'
     AND (a.resolution LIKE '%32 days%' OR a.resolution LIKE '%32 يوم%')
      THEN 'PATH_HOLD_AUTO_CLOSE_32D'
    WHEN a.ticket_status = 'Human review needed'
     AND a.resolution LIKE '%supporting proof%'
      THEN 'PATH_SETTLE_OR_PROOF_HUMAN_REVIEW'
    WHEN a.ticket_status = 'Closed' THEN 'PATH_OTHER_CLOSE'
    WHEN a.ticket_status = 'Human review needed' THEN 'PATH_OTHER_HUMAN_REVIEW'
